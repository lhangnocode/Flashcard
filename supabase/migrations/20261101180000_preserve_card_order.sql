-- Card order. One import inserts all its cards in one transaction, so they
-- share a single created_at and sorted in random (id) order. `position` is a
-- counter Postgres assigns on insert: rows from one multi-row insert get
-- increasing numbers in the order they were sent, and no two rows share one.
-- Numbers are global (a deck may have 1, 2, 3, 250, …); only the order matters.

alter table public.cards add column position bigint;

-- Backfill without touching updated_at.
alter table public.cards disable trigger cards_set_updated_at;

-- Cards from one import tie on created_at; ctid (physical row location) is a
-- best-effort tie-break: rows never updated since the import are usually
-- still in insert order, studied rows may have moved. Re-importing a deck
-- gives an exact order.
with ranked as (
  select id, row_number() over (order by created_at, ctid) as seq
  from public.cards
)
update public.cards c
set position = ranked.seq
from ranked
where c.id = ranked.id;

alter table public.cards enable trigger cards_set_updated_at;

alter table public.cards alter column position set not null;
-- "by default" (not "always") leaves room for manual reordering later.
alter table public.cards alter column position add generated by default as identity;
select setval(
  pg_get_serial_sequence('public.cards', 'position'),
  coalesce((select max(position) from public.cards), 0) + 1,
  false
);

-- Listing a deck in order. Also covers what cards_deck_idx did (deck lookups,
-- cascading deck deletes), so that index goes.
create index cards_deck_position_idx on public.cards (deck_id, position);
drop index public.cards_deck_idx;
