-- Multiple-choice quiz questions, imported per deck.
-- Same ownership pattern as cards: user_id on every row, and the composite
-- foreign key (deck_id, user_id) guarantees a question's deck belongs to the
-- same user, so RLS only has to compare user_id.

-- Exactly 4 non-blank options of at most 500 characters, in a flat array
-- (array_ndims: a 2x2 array also has cardinality 4).
create function public.valid_quiz_options(p_options text[])
returns boolean
language sql
immutable
set search_path = ''
as $$
  select array_ndims(p_options) = 1
     and cardinality(p_options) = 4
     and not exists (
       select 1 from unnest(p_options) as o
       where o is null or btrim(o) = '' or char_length(o) > 500
     );
$$;

create table public.quiz_questions (
  id            uuid primary key default gen_random_uuid(),
  deck_id       uuid not null,
  user_id       uuid not null references auth.users (id) on delete cascade,
  question      text not null
                  check (btrim(question) <> '' and char_length(question) <= 1000),
  options       text[] not null check (public.valid_quiz_options(options)),
  correct_index smallint not null check (correct_index between 0 and 3),
  explanation   text check (explanation is null or char_length(explanation) <= 5000),
  -- Import order. One import is one transaction, so created_at ties; this
  -- counter numbers rows in the order they were inserted.
  position      bigint generated by default as identity,
  created_at    timestamptz not null default now(),
  foreign key (deck_id, user_id)
    references public.decks (id, user_id) on delete cascade
);

-- Loading a deck's questions in order; also serves cascading deck deletes.
create index quiz_questions_deck_position_idx on public.quiz_questions (deck_id, position);

alter table public.quiz_questions enable row level security;

create policy "quiz_questions: select own" on public.quiz_questions for select to authenticated
  using ((select auth.uid()) = user_id);
create policy "quiz_questions: insert own" on public.quiz_questions for insert to authenticated
  with check ((select auth.uid()) = user_id);
create policy "quiz_questions: update own" on public.quiz_questions for update to authenticated
  using ((select auth.uid()) = user_id) with check ((select auth.uid()) = user_id);
create policy "quiz_questions: delete own" on public.quiz_questions for delete to authenticated
  using ((select auth.uid()) = user_id);

-- Supabase grants new tables to anon by default; signed-out visitors get nothing.
revoke all on public.quiz_questions from anon, authenticated;
grant select, insert, update, delete on public.quiz_questions to authenticated;

-- Adds questions to a deck, or replaces its whole set, in one transaction:
-- if the insert fails, the delete is rolled back too, so a deck is never
-- left empty. SECURITY INVOKER: RLS and the composite FK still apply (a deck
-- the caller doesn't own fails with 23503). Rows keep the array's order.
create function public.import_quiz_questions(
  p_deck_id uuid,
  p_questions jsonb,
  p_replace boolean default false
)
returns int
language plpgsql
security invoker
set search_path = ''
as $$
declare
  v_count int;
begin
  if jsonb_typeof(p_questions) is distinct from 'array'
     or jsonb_array_length(p_questions) not between 1 and 500 then
    raise exception 'expected 1 to 500 questions' using errcode = '22023';
  end if;

  if p_replace then
    delete from public.quiz_questions
    where deck_id = p_deck_id and user_id = (select auth.uid());
  end if;

  insert into public.quiz_questions (deck_id, user_id, question, options, correct_index, explanation)
  select
    p_deck_id,
    (select auth.uid()),
    q ->> 'question',
    array(select jsonb_array_elements_text(q -> 'options')),
    (q ->> 'correct_index')::smallint,
    nullif(q ->> 'explanation', '')
  from jsonb_array_elements(p_questions) with ordinality as t (q, n)
  order by n;

  get diagnostics v_count = row_count;
  return v_count;
end;
$$;

revoke execute on function public.import_quiz_questions(uuid, jsonb, boolean) from public, anon;
grant execute on function public.import_quiz_questions(uuid, jsonb, boolean) to authenticated;
